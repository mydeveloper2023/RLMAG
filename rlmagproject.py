def map_tag_to_layer(tag: str, dataset: str) -> str:
    """نگاشت کامل یک تگ به لایه‌ی IEC 62443."""
    tag_upper = tag.upper()

    # ==========================================
    # HAI Dataset
    # ==========================================
    if dataset == "HAI":
        if re.match(r"^P\d_B\d+", tag_upper):
            return "Layer 3 (Supervisory/SCADA)"
        if re.match(r"^X\d{4}_", tag_upper):
            return "Layer 3 (Supervisory/SCADA)"
        if any(k in tag_upper for k in [
            "MASW", "MANUALSD", "MANUALGO", "AUTOSD", "AUTOGO",
            "ONOFF", "TRIPEX", "RTR", "STSP", "EMERG", "SCST",
            "LH01", "LL01", "B400", "B300", "B200",
        ]):
            return "Layer 3 (Supervisory/SCADA)"
        if any(k in tag_upper for k in [
            "FCV", "LCV", "PCV", "PP0", "SOL", "SCO", "LCP01D",
        ]):
            return "Layer 2 (Communication/Control)"
        if any(k in tag_upper for k in [
            "FT", "LT", "LIT", "PT", "PIT",
            "TT", "TIT", "VIBTR", "SIT",
            "FIT", "PWIT", "TWIT", "VT",
        ]):
            return "Layer 1 (Field/Process)"
        if any(k in tag_upper for k in ["P4_HT", "P4_ST", "P4_LD"]):
            return "Layer 1 (Field/Process)"
        if any(k in tag_upper for k in ["LAMP", "24VDC"]):
            return "Layer 1 (Field/Process)"

    # ==========================================
    # HAIEnd Dataset
    # ==========================================
    if dataset == "HAIEnd":
        # --- Layer 3: Commands with -D suffix (any prefix) ---
        # پشتیبانی از DM-*-D، DQ03-*-D، و هر پیشوند دیگری
        if re.search(r"-D$", tag) or tag.endswith("-DEV"):
            return "Layer 3 (Supervisory/SCADA)"

        # --- Layer 2: Internal logic outputs ---
        if re.match(r"^\d{4}\.\d+", tag):
            return "Layer 2 (Communication/Control)"

        # --- Layer 2: Feedback/state ---
        if tag.endswith("-R") or tag.endswith("-Z"):
            return "Layer 2 (Communication/Control)"

        # --- Layer 2: Boolean commands & states ---
        if any(k in tag_upper for k in [
            "-DO", "-AO", "-SV", "-SP",
            "-ST", "-EM", "-MIS", "-START", "-STEP",
            "GATEOPEN", "CIP-1ST", "CIP-2ND", "CIPH",
            "COOL-ON", "SS01-RM", "ST-SP", "SW01", "SW02", "SW03",
        ]):
            return "Layer 2 (Communication/Control)"

        # --- Layer 1: Measurements ---
        if any(k in tag_upper for k in [
            "DM-FT", "DM-LT", "DM-PT", "DM-TT",
            "DM-PIT", "DM-LIT", "DM-TIT",
            "DM-TWIT", "DM-PWIT",
            "DM-LSH", "DM-LSL", "DM-AIT",
        ]):
            return "Layer 1 (Field/Process)"

    return "Unknown"


