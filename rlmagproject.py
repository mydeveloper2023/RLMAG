# سپس بردار احتمال s_i(x) ∈ [0,1] را استخراج می‌کنیم.
# ============================================================

def get_layer_probs(df, mapping, layer_name, seed=42, test_size=0.5):
    """
    استخراج احتمال پیش‌بینی مدل پایه برای یک لایه.

    Returns:
        probs: np.array of shape (n_test,) — s_i(x) ∈ [0,1]
        y_test: np.array of shape (n_test,) — برچسب‌ها
        clf: مدل آموزش‌دیده (برای دسترسی به feature importance)
        n_kept: تعداد تگ‌های نگه‌داشته‌شده
        n_dropped: تعداد تگ‌های حذف‌شده (zero variance)
    """
    tags = mapping[mapping["layer"] == layer_name]["tag"].tolist()
    tags = [t for t in tags if t in df.columns]

    X = df[tags].values
    y = df["label"].values

    # حذف تگ‌های ثابت (zero variance) — کاهش ابعاد
    var_mask = X.std(axis=0) > 1e-9
    X = X[:, var_mask]
    n_kept = int(var_mask.sum())
    n_dropped = int(len(var_mask) - n_kept)

    if X.shape[1] < 1:
        return None, None, None, 0, 0

    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=test_size, random_state=seed, stratify=y
    )

    scaler = StandardScaler()
    X_tr = scaler.fit_transform(X_tr)
    X_te = scaler.transform(X_te)

    clf = LogisticRegression(
        max_iter=1000,
        class_weight="balanced",
        random_state=seed,
    )
    clf.fit(X_tr, y_tr)

    probs = clf.predict_proba(X_te)[:, 1]
    return probs, y_te, clf, n_kept, n_dropped


