def compute_clcs(probs_dict, weights):
    """محاسبه‌ی CLCS با وزن‌های داده‌شده (طبق فرمول مقاله)."""
    clcs = np.zeros(len(next(iter(probs_dict.values()))))
    for layer, w in weights.items():
        if layer in probs_dict and w > 0:
            clcs += w * probs_dict[layer]
    return clcs


def evaluate_clcs(y_true, clcs_scores, fpr_target=0.05):
    """ارزیابی CLCS با AUC و DR@FPR."""
    auc = roc_auc_score(y_true, clcs_scores)
    fpr, tpr, _ = roc_curve(y_true, clcs_scores)
    idx = np.searchsorted(fpr, fpr_target)
    dr = tpr[idx] if idx < len(tpr) else tpr[-1]
    return auc, dr


