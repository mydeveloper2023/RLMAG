def attack_segments_summary(df, ts_col, name):
    """شمارش تعداد بازه‌های حمله و طول هر بازه."""
    df = df.sort_values(ts_col).reset_index(drop=True)
    is_attack = (df["label"].values == 1).astype(int)

    # تغییرات: 0→1 شروع، 1→0 پایان
    changes = np.diff(is_attack, prepend=0, append=0)
    starts = np.where(changes == 1)[0]
    ends = np.where(changes == -1)[0]

    if len(starts) == 0:
        return {
            "dataset": name,
            "n_segments": 0,
            "min_duration_s": 0,
            "max_duration_s": 0,
            "mean_duration_s": 0.0,
            "median_duration_s": 0.0,
            "total_attack_samples": int(is_attack.sum()),
            "coverage_pct": 100 * is_attack.sum() / len(is_attack),
        }

    durations = ends - starts

    return {
        "dataset": name,
        "n_segments": int(len(starts)),
        "min_duration_s": int(durations.min()),
        "max_duration_s": int(durations.max()),
        "mean_duration_s": float(durations.mean()),
        "median_duration_s": float(np.median(durations)),
        "total_attack_samples": int(is_attack.sum()),
        "coverage_pct": 100 * is_attack.sum() / len(is_attack),
    }

