def extract_events_v2(df, thresholds, feature_cols):
    """استخراج رویدادها با آستانه‌های μ±2σ و μ±3σ."""
    events = {}
    for col in feature_cols:
        if col not in thresholds:
            continue

        t = thresholds[col]
        vals = df[col].values
        sigma = t["sigma"]

        # پیش‌فرض: NORMAL
        event_codes = np.full(len(vals), "NORMAL", dtype=object)

        if sigma > 1e-9:
            # VERY_LOW: x < μ - 3σ
            event_codes[vals < t["th_neg3"]] = "VERY_LOW"

            # LOW: μ - 3σ ≤ x < μ - 2σ
            mask_low = (vals >= t["th_neg3"]) & (vals < t["th_neg2"])
            event_codes[mask_low] = "LOW"

            # HIGH: μ + 2σ < x ≤ μ + 3σ
            mask_high = (vals > t["th_pos2"]) & (vals <= t["th_pos3"])
            event_codes[mask_high] = "HIGH"

            # VERY_HIGH: x > μ + 3σ
            event_codes[vals > t["th_pos3"]] = "VERY_HIGH"

        events[col] = event_codes

    return pd.DataFrame(events, index=df.index)


