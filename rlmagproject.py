def label_distribution(df, split_name):
    counts = df["label"].value_counts().sort_index()
    total = counts.sum()
    return {
        "split": split_name,
        "n_total": int(total),
        "n_normal": int(counts.get(0, 0)),
        "n_attack": int(counts.get(1, 0)),
        "pct_normal": 100 * counts.get(0, 0) / total,
        "pct_attack": 100 * counts.get(1, 0) / total,
    }

def split_test_by_time(df, ts_col="timestamp"):
    test1_mask = df[ts_col] < pd.Timestamp("2022-08-15")
    return df[test1_mask].copy(), df[~test1_mask].copy()

