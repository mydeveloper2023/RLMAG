def compute_metrics(y_true, y_prob, fpr_target=0.05):
    auc = roc_auc_score(y_true, y_prob)
    ap = average_precision_score(y_true, y_prob)

    fpr, tpr, thr = roc_curve(y_true, y_prob)
    idx = np.searchsorted(fpr, fpr_target)
    dr = tpr[idx] if idx < len(tpr) else tpr[-1]
    actual_fpr = fpr[idx] if idx < len(fpr) else fpr[-1]
    threshold = thr[idx] if idx < len(thr) else thr[-1]

    y_pred = (y_prob >= threshold).astype(int)
    return {
        "auc_roc": auc,
        "auc_pr": ap,
        "dr_at_fpr5": dr,
        "actual_fpr": actual_fpr,
        "f1": f1_score(y_true, y_pred),
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
    }


