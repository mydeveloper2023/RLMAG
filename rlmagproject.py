def compute_corr_matrix(probs_dict, layers):
    """محاسبه‌ی ماتریس همبستگی Pearson بین لایه‌ها."""
    mat = pd.DataFrame(index=layers, columns=layers, dtype=float)
    p_values = pd.DataFrame(index=layers, columns=layers, dtype=float)

    for i, l1 in enumerate(layers):
        for j, l2 in enumerate(layers):
            if l1 in probs_dict and l2 in probs_dict:
                if i == j:
                    mat.loc[l1, l2] = 1.0
                    p_values.loc[l1, l2] = 0.0
                else:
                    r, p = pearsonr(probs_dict[l1], probs_dict[l2])
                    mat.loc[l1, l2] = r
                    p_values.loc[l1, l2] = p
    return mat, p_values


