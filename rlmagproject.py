import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import roc_curve, roc_auc_score
from sklearn.model_selection import train_test_split
from scipy.stats import ks_2samp, wasserstein_distance

print("=" * 90)
print("PHASE 2 — SECTION 6.2: LAYER-WISE DISCRIMINABILITY")
print("=" * 90)

# ============================================================
# تابع کمکی: محاسبه‌ی معیارهای discriminability برای یک لایه
# ============================================================
def compute_layer_discriminability(df, layer_name, dataset_name):
    """
    محاسبه‌ی معیارهای discriminability برای یک لایه.

    رویکرد: یک مدل Logistic Regression ساده روی تگ‌های همان لایه
    آموزش می‌دهیم و AUC را روی test محاسبه می‌کنیم.
    """
    # انتخاب تگ‌های همان لایه
    if dataset_name == "HAI":
        mapping = hai_mapping
    else:
        mapping = haiend_mapping

    layer_tags = mapping[mapping["layer"] == layer_name]["tag"].tolist()
    layer_tags = [t for t in layer_tags if t in df.columns]

    if len(layer_tags) < 2:
        return None

    # ویژگی‌ها و برچسب
    X = df[layer_tags].values
    y = df["label"].values

    # حذف تگ‌های ثابت (zero variance)
    var_mask = X.std(axis=0) > 1e-9
    X = X[:, var_mask]
    kept_tags = np.array(layer_tags)[var_mask]

    if X.shape[1] < 1:
        return None

    # تقسیم train/test (روی داده test اصلی، split می‌کنیم)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.5, random_state=42, stratify=y
    )

    # استانداردسازی
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # آموزش مدل
    clf = LogisticRegression(max_iter=1000, class_weight="balanced",
                              random_state=42)
    clf.fit(X_train_scaled, y_train)

    # پیش‌بینی
    y_prob = clf.predict_proba(X_test_scaled)[:, 1]

    # محاسبه‌ی معیارها
    auc = roc_auc_score(y_test, y_prob)

    # DR @ FPR=5%
    fpr, tpr, thr = roc_curve(y_test, y_prob)
    idx = np.searchsorted(fpr, 0.05)
    dr_at_5 = tpr[idx] if idx < len(tpr) else tpr[-1]

    # KS و Wasserstein (روی probability scores)
    pos = y_prob[y_test == 1]
    neg = y_prob[y_test == 0]

    ks_stat, _ = ks_2samp(pos, neg)
    wass = wasserstein_distance(pos, neg)

    return {
        "dataset": dataset_name,
        "layer": layer_name,
        "n_tags": len(kept_tags),
        "n_dropped": len(layer_tags) - len(kept_tags),
        "auc_roc": auc,
        "dr_at_fpr5": dr_at_5,
        "ks_stat": ks_stat,
        "wasserstein": wass,
        "roc_data": (fpr, tpr),
        "y_prob_pos": pos,
        "y_prob_neg": neg,
    }


