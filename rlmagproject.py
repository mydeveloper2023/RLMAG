print("\n[Step 3] Training layer-wise probes (correct index alignment)...")

def get_layer_probs_correct(df, mapping, layer_name,
                              train_idx, test_idx, y_tr):
    """استخراج probability لایه‌ای با ایندکس صحیح."""
    tags = mapping[mapping["layer"] == layer_name]["tag"].tolist()
    tags = [t for t in tags if t in df.columns]

    X_layer = df[tags].values
    var_mask = X_layer.std(axis=0) > 1e-9
    X_layer = X_layer[:, var_mask]

    if X_layer.shape[1] < 1:
        return None

    # ایندکس‌های موقعیتی
    df_idx_to_pos = {idx: i for i, idx in enumerate(df.index.values)}
    tr_pos = np.array([df_idx_to_pos[i] for i in train_idx])
    te_pos = np.array([df_idx_to_pos[i] for i in test_idx])

    X_l_tr = X_layer[tr_pos]
    X_l_te = X_layer[te_pos]

    scaler = StandardScaler()
    X_l_tr = scaler.fit_transform(X_l_tr)
    X_l_te = scaler.transform(X_l_te)

    clf = LogisticRegression(max_iter=1000, class_weight="balanced",
                              random_state=42)
    clf.fit(X_l_tr, y_tr)
    return clf.predict_proba(X_l_te)[:, 1]


