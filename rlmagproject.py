def extract_thresholds(train_df, feature_cols):
    """استخراج μ و σ برای هر تگ از داده‌ی نرمال train."""
    thresholds = {}
    for col in feature_cols:
        vals = train_df[col].values
        mu = vals.mean()
        sigma = vals.std()
        thresholds[col] = {
            "mu": mu,
            "sigma": sigma,
            "th_neg3": mu - 3*sigma,
            "th_neg2": mu - 2*sigma,
            "th_pos2": mu + 2*sigma,
            "th_pos3": mu + 3*sigma,
        }
    return thresholds


