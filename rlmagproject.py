def load_and_align_ts(df, ts_col, target_col='timestamp'):
    """
    تبدیل ستون زمان به datetime، حذف مقادیر نامعتبر،
    و یکسان‌سازی نام ستون زمان به target_col.
    """
    df = df.copy()

    if ts_col not in df.columns:
        raise KeyError(
            f"Timestamp column '{ts_col}' not found. "
            f"Available columns: {df.columns[:5].tolist()}..."
        )

    # تبدیل به datetime با فرمت انعطاف‌پذیر
    df[ts_col] = pd.to_datetime(df[ts_col], errors='coerce')
    df = df.dropna(subset=[ts_col])

    # یکسان‌سازی نام ستون زمان
    if ts_col != target_col:
        df = df.rename(columns={ts_col: target_col})

    return df


def load_many_csv(files, ts_col):
    """بارگذاری و concat چند فایل CSV با ستون زمان مشخص."""
    frames = []
    for f in files:
        df = pd.read_csv(f)
        df = load_and_align_ts(df, ts_col)
        frames.append(df)
        print(f"  {f.name}: {df.shape}")

    if not frames:
        raise FileNotFoundError("No CSV files found for the given pattern.")

    return pd.concat(frames, ignore_index=True)


